def generate_time_shift_matrix(degree):
    """
    Generates S^T to map polynomial coefficients from the t in [0, 1] domain 
    to the tau in [-1, 1] domain using the relation tau = 2t - 1.
    """
    S = np.zeros((degree + 1, degree + 1))
    for j in range(degree + 1):
        for k in range(j + 1):
            S[k, j] = math.comb(j, k) * (2**k) * ((-1)**(j - k))
    return S.T


def print_fraction_matrix(matrix, name):
    """Formats the SymPy array into a clean, copy-pasteable NumPy array with fractions."""
    print(f"{name} = np.array([")
    for row in matrix:
        row_str = "    ["
        for val in row:
            # Limit the denominator to prevent absurdly long fractions in higher degrees
            frac = Fraction(float(val)).limit_denominator(1000000)
            if frac.denominator == 1:
                row_str += f"{frac.numerator:>4}.0, "
            else:
                row_str += f"{frac.numerator:>4}/{frac.denominator:<4}, "
        row_str = row_str.rstrip(", ") + "],"
        print(row_str)
    print("])\n")

def generate_all_clamped_matrices(degree):
    d = degree
    
    # Create a knot vector long enough to stabilize in the middle.
    # We need 'd' start segments, 'd' end segments, and a few interior ones.
    total_spans = 2 * d + 2
    
    # Build the clamped knot vector: 
    # [0,0,0... 1, 2, 3... max, max, max...]
    knots = [0] * (d + 1) + list(range(1, total_spans)) + [total_spans] * (d + 1)
    
    u = sp.Symbol('u')
    t = sp.Symbol('t')
    
    print(f"=============================================")
    print(f" GENERATING CLAMPED MATRICES FOR DEGREE {degree}")
    print(f"=============================================\n")
    
    # Loop through every physical segment of the curve
    for span_idx in range(total_spans):
        target_start = knots[d + span_idx]
        target_end = knots[d + span_idx + 1]
        
        # The Cox-de Boor Recursive Algorithm
        def N(i, p):
            if p == 0:
                # 1 if 'u' is inside this specific span, 0 otherwise
                if knots[i] <= target_start and knots[i+1] >= target_end and knots[i] < knots[i+1]:
                    return sp.S(1)
                return sp.S(0)
            
            term1 = sp.S(0)
            if knots[i+p] - knots[i] > 0:
                term1 = ((u - knots[i]) / (knots[i+p] - knots[i])) * N(i, p-1)
                
            term2 = sp.S(0)
            if knots[i+p+1] - knots[i+1] > 0:
                term2 = ((knots[i+p+1] - u) / (knots[i+p+1] - knots[i+1])) * N(i+1, p-1)
                
            return term1 + term2

        # In span 'j', the active basis functions are from 'j-d' to 'j'
        j = d + span_idx
        basis_funcs = [N(i, d) for i in range(j - d, j + 1)]
        
        # Convert from global time 'u' to local segment time 't' (0 to 1)
        local_basis_funcs = [sp.expand(bf.subs(u, t + target_start)) for bf in basis_funcs]
        
        # Extract the polynomial coefficients into a matrix
        M = []
        for poly in local_basis_funcs:
            coeffs = sp.Poly(poly, t).all_coeffs()
            coeffs = coeffs[::-1] # Reverse to [t^0, t^1, ..., t^d]
            while len(coeffs) < d + 1:
                coeffs.append(sp.S(0))
            M.append(coeffs)
            
        # Transpose so that rows match the polynomial powers [1, t, t^2, ...]
        M_transposed = []
        for row_idx in range(d + 1):
            row = [M[col_idx][row_idx] for col_idx in range(d + 1)]
            M_transposed.append(row)
            
        # Name the matrices intelligently based on their position
        if span_idx < d:
            name = f"M{degree}_start_{span_idx}"
        elif span_idx >= total_spans - d:
            # Reverses the index so the very last segment is M{degree}_end_0
            end_idx = total_spans - span_idx - 1
            name = f"M{degree}_end_{end_idx}"
        else:
            # We only need to print the interior matrix once, as it repeats
            if span_idx == d: 
                name = f"M{degree}_interior"
            else:
                continue 
            
        print_fraction_matrix(M_transposed, name)

